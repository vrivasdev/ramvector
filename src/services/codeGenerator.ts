export function convertToReact(svgString: string, componentName = 'SvgIcon'): string {
  let jsx = svgString;

  for (const [kebab, camel] of Object.entries(ATTRIBUTE_MAP)) {
    const regex = new RegExp(`\\b${kebab}=`, 'g');
    jsx = jsx.replace(regex, `${camel}=`);
  }

  // Insert {...props} into the opening <svg tag
  jsx = jsx.replace(/<svg\b([^>]*)>/, '<svg$1 {...props}>');

  return `import React from 'react';

export interface ${componentName}Props extends React.SVGProps<SVGSVGElement> {}

export const ${componentName}: React.FC<${componentName}Props> = (props) => (
  ${jsx.trim()}
);

export default ${componentName};`;
}

export function convertToVue(svgString: string): string {
  return `<template>
  ${svgString.trim()}
</template>

<script setup lang="ts">
// Generated by RamVector In-RAM Optimizer
</script>`;
}

export function convertToSvelte(svgString: string): string {
  let svelte = svgString.trim();
  // Using restProps for Svelte SVG spreading
  svelte = svelte.replace(/<svg\b([^>]*)>/, '<svg$1 {...$$$$restProps}>');
  return svelte;
}

export function convertToDataUri(svgString: string): string {
  const minified = svgString.replace(/\s+/g, ' ').trim();
  const encoded = encodeURIComponent(minified)
    .replace(/'/g, '%27')
    .replace(/"/g, '%22');
  return `data:image/svg+xml,${encoded}`;
}

export function generateExportCode(svgString: string, format: ExportFormat, name = 'SvgIcon'): string {
  switch (format) {
    case 'raw':
      return svgString.trim();
    case 'react':
      return convertToReact(svgString, name);
    case 'vue':
      return convertToVue(svgString);
    case 'svelte':
      return convertToSvelte(svgString);
    case 'datauri':
      return convertToDataUri(svgString);
    default:
      return svgString.trim();
  }
}
